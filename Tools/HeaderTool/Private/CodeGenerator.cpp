#include "CodeGenerator.h"

#include <cstddef>
#include <format>
#include <string_view>
#include <vector>

namespace
{
	/** Returns "EnumName::A | EnumName::B", or "EnumName::None" for no flags. */
	std::string FormatFlags(std::string_view EnumName, const std::vector<std::string>& Flags)
	{
		if (Flags.empty())
		{
			return std::format("{}::None", EnumName);
		}

		std::string Text;
		for (const std::string& Flag : Flags)
		{
			if (!Text.empty())
			{
				Text += " | ";
			}
			Text += std::format("{}::{}", EnumName, Flag);
		}
		return Text;
	}

	void AppendProperty(std::string& Output, const FReflectedClass& Class, const FReflectedProperty& Property)
	{
		Output +=
			std::format("\tClass.AddProperty(MakeProperty<&{}::{}>(\"{}\"", Class.Name, Property.Name, Property.Name);

		const bool bHasSpecifiers = !Property.Flags.empty() || !Property.Category.empty();
		if (bHasSpecifiers)
		{
			Output += std::format(",\n\t\tFPropertySpecifiers{{.Flags = {}, .Category = \"{}\"}}",
				FormatFlags("EPropertyFlags", Property.Flags),
				Property.Category);
		}

		Output += "));\n";
	}

	void AppendFunction(std::string& Output, const FReflectedClass& Class, const FReflectedFunction& Function)
	{
		Output += std::format(
			"\tClass.AddFunction(MakeFunction<&{}::{}>(\"{}\",\n\t\t{{", Class.Name, Function.Name, Function.Name);

		for (std::size_t Index = 0; Index < Function.ParameterNames.size(); ++Index)
		{
			Output += std::format("{}\"{}\"", Index > 0 ? ", " : "", Function.ParameterNames[Index]);
		}

		Output += std::format("}},\n\t\tFFunctionSpecifiers{{.Flags = {}, .Category = \"{}\"}}));\n",
			FormatFlags("EFunctionFlags", Function.Flags),
			Function.Category);
	}

	void AppendClass(std::string& Output, const FReflectedClass& Class)
	{
		Output += std::format("\nWW_IMPLEMENT_CLASS({})\n\n", Class.Name);
		Output += std::format("void {}::RegisterClassMembers([[maybe_unused]] WClass& Class)\n{{\n", Class.Name);

		for (const FReflectedProperty& Property : Class.Properties)
		{
			AppendProperty(Output, Class, Property);
		}
		for (const FReflectedFunction& Function : Class.Functions)
		{
			AppendFunction(Output, Class, Function);
		}

		Output += "}\n";
	}
}

std::string FCodeGenerator::Generate(std::span<const FReflectedHeader> Headers)
{
	std::string Output =
		"// Generated by WhiteWolfHeaderTool from the WCLASS(), WPROPERTY() and WFUNCTION() declarations "
		"of this module.\n"
		"// Do not edit this file: every build writes it again.\n";

	bool bHasClasses = false;
	for (const FReflectedHeader& Header : Headers)
	{
		if (!Header.Classes.empty())
		{
			Output += std::format("{}#include \"{}\"\n", bHasClasses ? "" : "\n", Header.IncludePath);
			bHasClasses = true;
		}
	}
	if (!bHasClasses)
	{
		return Output;
	}

	Output += "\n"
			  "#include \"Object/ObjectMacros.h\"\n"
			  "#include \"Reflection/FunctionFactory.h\"\n"
			  "#include \"Reflection/PropertyFactory.h\"\n";

	for (const FReflectedHeader& Header : Headers)
	{
		for (const FReflectedClass& Class : Header.Classes)
		{
			AppendClass(Output, Class);
		}
	}

	return Output;
}
