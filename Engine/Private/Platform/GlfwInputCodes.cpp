#define WW_CHECK_KEY_CODE(EngineName, GlfwName) \
	static_assert(static_cast<int>(EKey::EngineName) == GLFW_KEY_##GlfwName, \
		"EKey::" #EngineName " does not have the value of GLFW_KEY_" #GlfwName)

